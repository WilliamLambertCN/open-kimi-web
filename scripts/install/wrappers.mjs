import { isAbsolute } from 'node:path';

const MARKER = 'open-kimi-web integration wrapper';

export function shQuote(value) {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

export function installerCommand(ctx, command) {
  const quote = ctx.platform === 'win32' ? (value) => `'${value.replaceAll("'", "''")}'` : shQuote;
  return `${ctx.platform === 'win32' ? '& ' : ''}${quote(ctx.node)} ${quote(ctx.entry)} ${command}`;
}

function shWrapper({ entry, realKimi, node }, kimi) {
  const label = kimi ? 'wrapper' : 'launcher';
  const verb = kimi ? '__wrap ' : '';
  const real = kimi ? `OPEN_KIMI_REAL_KIMI=${shQuote(realKimi)}\nexport OPEN_KIMI_REAL_KIMI\n` : '';
  return `#!/bin/sh
# ${MARKER} — generated by \`open-kimi-web integrate install\`.
# Do not edit; regenerate with \`open-kimi-web integrate repair\`.
${real}if [ -x ${shQuote(node)} ]; then
  exec ${shQuote(node)} ${shQuote(entry)} ${verb}"$@"
elif command -v node >/dev/null 2>&1; then
  exec node ${shQuote(entry)} ${verb}"$@"
else
  echo "open-kimi-web ${label}: node executable not found; run: open-kimi-web integrate repair" >&2
  exit 127
fi
`;
}

function cmdWrapper({ entry, realKimi, node }, kimi) {
  const label = kimi ? 'wrapper' : 'launcher';
  const verb = kimi ? '__wrap ' : '';
  const real = kimi ? `set "OPEN_KIMI_REAL_KIMI=${realKimi}"\n` : '';
  return `@echo off
rem ${MARKER} — generated by "open-kimi-web integrate install".
rem Do not edit; regenerate with "open-kimi-web integrate repair".
${real}if exist "${node}" goto recorded
where node >nul 2>nul
if errorlevel 1 goto nonode
node "${entry}" ${verb}%*
exit /b %ERRORLEVEL%
:recorded
"${node}" "${entry}" ${verb}%*
exit /b %ERRORLEVEL%
:nonode
echo open-kimi-web ${label}: node executable not found; run: open-kimi-web integrate repair 1>&2
exit /b 127
`;
}

function entryToken(text, platform) {
  if (platform === 'win32') return /\n"[^"\n]+" "([^"\n]+)" (?:__wrap )?%\*\n/.exec(text)?.[1];
  const quoted = "'(?:[^']|'\\\\'')*'";
  const match = new RegExp(`\\n  exec ${quoted} (${quoted}) (?:__wrap )?"\\$@"\\n`).exec(text);
  return match?.[1].slice(1, -1).replaceAll("'\\''", "'");
}

export function wrapperEntry(text, state, ctx, kimi) {
  const normalized = text.replaceAll('\r\n', '\n');
  const entry = entryToken(normalized, ctx.platform);
  if (!entry || !isAbsolute(entry) || !entry.endsWith('open-kimi-web.mjs')) return null;
  const fields = { entry, node: state.node, realKimi: state.realKimi };
  const expected = ctx.platform === 'win32' ? cmdWrapper(fields, kimi) : shWrapper(fields, kimi);
  return normalized === expected ? entry : null;
}
